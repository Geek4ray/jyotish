"""Generate the placement rule library (SPEC Layer 6b, order of work item 4) from one table,
scripts/placements.csv, so the astrologer's triage edits the table and regenerates:

    .venv/bin/python scripts/make_placements.py                 # writes rules/place.*.yaml
    .venv/bin/python scripts/make_placements.py --check         # exit 1 if a file differs from the table
    .venv/bin/python scripts/make_placements.py --triage        # (re)writes scripts/placements_triage.csv
    .venv/bin/python scripts/make_placements.py --merge-triage  # copies the filled sheet into the table

Promotion (SPEC Layer 3): a row is `draft` (fires, is recorded, is narrated as a placement fact
only, carries no weight) until it records who read its verse in the named edition and when
(verse_read_by, verse_read_on) and the reader's verdict on the effect line (effect_confirmed:
yes, or changed with the line rewritten); then it is classical_unconfirmed with its source
checked: true, read_by and read_on. A promoted row must also name its verse. effect_confirmed
no keeps the row a draft (the note says why). practitioner_note goes into the source's note.

Rows: lord-in-house (BPHS chapter 24, Santhanam 1984; ids place.l<N>_h<M>, the lord of the
N-th in the M-th, `when: {lord_of: [N], house: M}`) and planet-in-house (Phaladeepika chapter
8, Sastri 1937; ids place.<planet>_h<M>). Basis lagna only: from the Moon and the Sun the same
placements would fire three times, and Sudarshana stays with the yogas.

Columns: id, kind (lord | planet), lord_of, planet, house, names (|-separated words a tagged
sentence must contain), themes (theme:signed value;... on the existing theme names, |value| at
most 2), outcomes (|-separated), modifiers (|-separated codes: debilitated x0.5, enemy x0.8,
combust x0.5, mks (marana karaka sthana) x0.6; retrograde is not reduced: the texts read a
retrograde planet as strong in motion), text, edition, chapter, verse, checked, narration_key
(the classical effect in the engine's own words, one line; no translation is quoted),
verse_read_by, verse_read_on (YYYY-MM-DD), effect_confirmed (yes | no | changed), practitioner_note.

The first version of the table was drafted by the engine from the principles these chapters
apply (a lord carries its house's matters into the house it occupies; kendras, trikonas, the
2nd and 11th support; a lord in the 6th, 8th or 12th strains its own matters; a dusthana lord
in another dusthana is the viparita case; natural benefics are strong in kendras and trikonas,
malefics in the upachayas 3, 6, 10, 11). Every source is `checked: false` with its verse "not
yet located" until it is read in the named edition: the triage is what makes a row the text's.
Every rule: confidence_base 0.3 (a single placement never outweighs a yoga)."""

from __future__ import annotations

import csv
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
TABLE = ROOT / "scripts" / "placements.csv"
TRIAGE = ROOT / "scripts" / "placements_triage.csv"
TRIAGE_COLUMNS = ["id", "placement", "draft_effect", "verse_reference", "verse_read_by", "verse_read_on",
                  "effect_confirmed", "practitioner_note"]
PROMOTION = ["verse_read_by", "verse_read_on", "effect_confirmed", "practitioner_note"]
ORD = {1: "1st", 2: "2nd", 3: "3rd"} | {n: f"{n}th" for n in range(4, 13)}
RULES = ROOT / "rules"
MODIFIERS = {
    "debilitated": {"if": {"dignity": "debilitated"}, "scale": 0.5},
    "enemy": {"if": {"dignity": "enemy"}, "scale": 0.8},
    "combust": {"if": "combust", "scale": 0.5},
    "mks": {"if": "marana_karaka_sthana", "scale": 0.6},
}
FAMILY = {"lord": "lord_in_house", "planet": "planet_in_house"}
HEADER = "# Generated by scripts/make_placements.py from scripts/placements.csv: edit the table, not this file.\n"


def promoted(row: dict) -> bool:
    """A row is promoted when a named reader read its verse on a given date and confirmed (or
    rewrote) the effect line."""
    who, when, verdict = (row.get(k, "").strip() for k in ("verse_read_by", "verse_read_on", "effect_confirmed"))
    if verdict and verdict not in ("yes", "no", "changed"):
        raise ValueError(f"{row['id']}: effect_confirmed must be yes, no or changed, not {verdict!r}")
    if when and not re.fullmatch(r"\d{4}-\d{2}-\d{2}", when):
        raise ValueError(f"{row['id']}: verse_read_on must be YYYY-MM-DD, not {when!r}")
    ok = bool(who and when and verdict in ("yes", "changed"))
    if ok and row["verse"].strip() in ("", "not yet located"):
        raise ValueError(f"{row['id']}: promoted by {who} but the verse is not named")
    return ok


def placement_words(row: dict) -> str:
    house = ORD[int(row["house"])]
    if row["kind"] == "lord":
        return f"the lord of the {ORD[int(row['lord_of'])]} in the {house}"
    return f"{'the ' if row['planet'] in ('Sun', 'Moon') else ''}{row['planet']} in the {house}"


def verse_reference(row: dict) -> str:
    v = row["verse"].strip()
    where = f", verse {v}" if v and v != "not yet located" else f", {placement_words(row)} (verse not yet located)"
    return f"{row['text']} ({row['edition']}), chapter {row['chapter']}{where}"


def rule(row: dict) -> dict:
    when = ({"lord_of": [int(row["lord_of"])]} if row["kind"] == "lord" else {"planet": row["planet"]})
    when |= {"house": int(row["house"]), "basis": ["lagna"]}
    themes = {}
    for part in filter(None, row["themes"].split(";")):
        name, value = part.split(":")
        v = int(value)
        if abs(v) > 2:
            raise ValueError(f"{row['id']}: theme {name} {v} beyond the +-2 cap")
        themes[name] = v
    up = promoted(row)
    src = {"text": row["text"], "edition": row["edition"], "chapter": int(row["chapter"]), "verse": row["verse"],
           "checked": up}
    if up:
        src |= {"read_by": row["verse_read_by"].strip(), "read_on": row["verse_read_on"].strip()}
    if row.get("practitioner_note", "").strip():
        src["note"] = row["practitioner_note"].strip()
    out = {"id": row["id"], "family": FAMILY[row["kind"]], "school": "parashari",
           "names": row["names"].split("|"), "source": [src],
           "status": "classical_unconfirmed" if up else "draft", "when": when}
    mods = [MODIFIERS[m] for m in filter(None, row["modifiers"].split("|"))]
    if mods:
        out["modifiers"] = mods
    out |= {"themes": themes, "outcomes": row["outcomes"].split("|"), "confidence_base": 0.3,
            "narration_key": row["narration_key"]}
    return out


def render(row: dict) -> str:
    return HEADER + yaml.safe_dump(rule(row), sort_keys=False, allow_unicode=True, width=200, default_flow_style=None)


def write_triage() -> int:
    """The astrologer's sheet: one row per rule, the placement in words, the draft effect line,
    the verse reference, and the four columns he fills. Entries already filled are kept."""
    rows = list(csv.DictReader(TABLE.open(newline="")))
    old = {r["id"]: r for r in csv.DictReader(TRIAGE.open(newline=""))} if TRIAGE.exists() else {}
    with TRIAGE.open("w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=TRIAGE_COLUMNS, lineterminator="\n")
        w.writeheader()
        for r in rows:
            kept = old.get(r["id"], {})
            w.writerow({"id": r["id"], "placement": placement_words(r),
                        "draft_effect": kept.get("draft_effect") or r["narration_key"],
                        "verse_reference": verse_reference(r),
                        **{c: kept.get(c, "") or r.get(c, "") for c in PROMOTION}})
    print(f"{len(rows)} rows -> {TRIAGE.name}")
    return 0


def merge_triage() -> int:
    """Copy the filled sheet into the table: the four columns, and the effect line where the
    reader marked it changed."""
    sheet = {r["id"]: r for r in csv.DictReader(TRIAGE.open(newline=""))}
    rows = list(csv.DictReader(TABLE.open(newline="")))
    merged = 0
    for r in rows:
        t = sheet.get(r["id"])
        if not t:
            continue
        before = dict(r)
        for c in PROMOTION:
            r[c] = t.get(c, "").strip()
        if r["effect_confirmed"] == "changed" and t.get("draft_effect", "").strip():
            r["narration_key"] = t["draft_effect"].strip()
        merged += r != before
    with TABLE.open("w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]), lineterminator="\n")
        w.writeheader()
        w.writerows(rows)
    print(f"{merged} row(s) of {TABLE.name} updated from {TRIAGE.name}; regenerate the rules next")
    return 0


def main(check: bool = False) -> int:
    rows = list(csv.DictReader(TABLE.open(newline="")))
    ids = [r["id"] for r in rows]
    if len(ids) != len(set(ids)):
        raise ValueError("duplicate ids in the table")
    differ = []
    for row in rows:
        path = RULES / f"{row['id']}.yaml"
        text = render(row)
        if not path.exists() or path.read_text() != text:
            differ.append(path.name)
            if not check:
                path.write_text(text)
    stale = sorted(p.name for p in RULES.glob("place.*.yaml") if p.stem not in set(ids))
    for name in stale:
        differ.append(name)
        if not check:
            (RULES / name).unlink()
    if check:
        print(f"{len(differ)} file(s) differ from the table" + (f": {', '.join(differ[:5])}" if differ else ""))
        return 1 if differ else 0
    print(f"{len(rows)} rules from {TABLE.name}; {len(differ)} written or removed")
    return 0


if __name__ == "__main__":
    if "--triage" in sys.argv:
        sys.exit(write_triage())
    if "--merge-triage" in sys.argv:
        sys.exit(merge_triage())
    sys.exit(main(check="--check" in sys.argv))
